pub trait NetabaseModelKeys<
    R: NetabaseRepository,
    D: NetabaseDefinition<R>,
    M: NetabaseModelWithKeys<R, D>,
> where
    Self: strum::IntoDiscriminant,
{
    type PrimaryKey: PrimaryKey<R, D, M>;
    type SecondaryKeys: SecondaryKeysEnum<R, D, M>;
    type RelationalKeys: RelationalKeysEnum<R, D, M>;
    type SubscriptionKeys: SubscriptionKeysEnum<R, M>;
    type BlobKeys: BlobKeysEnum<R, D, M>;
}

