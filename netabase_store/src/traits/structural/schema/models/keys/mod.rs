pub trait ModelKeysStorageMode<
    R: NetabaseRepository,
    D: NetabaseDefinition<R>,
    M: NetabaseModelWithKeys<R, D>,
>: NodeStorageMode
{
    const PRIMARY_MODE: TableStorageMode = TableStorageMode::Linear;
    const SECONDARY_MODE: TableStorageMode = TableStorageMode::Sharded;
    const RELATIONAL_MODE: TableStorageMode = TableStorageMode::Sharded;
    const SUBSCRIPTION_MODE: TableStorageMode = TableStorageMode::Sharded;
    const BLOB_MODE: TableStorageMode = TableStorageMode::Sharded;
}

pub trait NetabaseDefinitionKeys<R: NetabaseRepository, D: NetabaseDefinition<R>> {
    type PrimaryKey: TableKey;
    type SecondaryKeys: DefinitionSecondaryKeys<R, D>;
    type RelationalKeys: DefinitionRelationalKeys<R, D>;
    type BlobKeys: DefinitionBlobKeys<R, D>;
    type SubscriptionKeys: DefinitionSubscriptionKeys<R, D>;
}
pub trait NetabaseRepositoryKeys<R: NetabaseRepository> {
    type PrimaryKey: TableKey;
    type SecondaryKeys: RepositorySecondaryKeys<R>;
    type RelationalKeys: RepositoryRelationalKeys<R>;
    type BlobKeys: RepositoryBlobKeys<R>;
    type SubscriptionKeys: RepositorySubscriptionKeys<R>;
}

